using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.Rendering;

namespace Deadzone.Visuals
{
    /// <summary>
    /// One graphics preset. Heavy settings (render scale, MSAA, shadow resolution/distance, SSAO) live in the URP asset that
    /// 'pipelineAsset' points to; the rest is applied by GraphicsSettingsService / GraphicsApplier. All numbers are TARGETS that
    /// were not measured on a device yet (see PERFORMANCE_BUDGET.md).
    /// </summary>
    [Serializable]
    public sealed class GraphicsProfile
    {
        public GraphicsQuality quality;
        public RenderPipelineAsset pipelineAsset;
        public VolumeProfile volumeProfile;
        public bool postProcessing;
        public bool softShadows;
        public int targetFrameRate = 30;
        public float lodBias = 1f;
        public bool fog = true;
        public float fogDensity = 0.0022f;

        public bool HasVolume => volumeProfile != null;
        public bool HasPipeline => pipelineAsset != null;

        public static GraphicsProfile Fallback(GraphicsQuality quality)
        {
            switch (quality)
            {
                case GraphicsQuality.Low:
                    return new GraphicsProfile { quality = quality, targetFrameRate = 30, lodBias = 0.7f, fog = false, postProcessing = false, softShadows = false };
                case GraphicsQuality.Medium:
                    return new GraphicsProfile { quality = quality, targetFrameRate = 45, lodBias = 1f, fog = true, postProcessing = false, softShadows = false };
                default:
                    return new GraphicsProfile { quality = quality, targetFrameRate = 60, lodBias = 1.4f, fog = true, postProcessing = false, softShadows = true };
            }
        }
    }

    /// <summary>Resources/GraphicsProfiles.asset: the Low/Medium/High presets (generated by Tools > DEADZONE > Setup Lighting Profiles).</summary>
    public sealed class GraphicsProfileSet : ScriptableObject
    {
        public List<GraphicsProfile> profiles = new List<GraphicsProfile>();

        public GraphicsProfile Get(GraphicsQuality quality)
        {
            foreach (GraphicsProfile profile in profiles)
            {
                if (profile != null && profile.quality == quality) return profile;
            }
            return GraphicsProfile.Fallback(quality);
        }
    }
}
